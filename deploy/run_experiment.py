"""
run_experiment.py — Real-cluster validation: RL controller vs native HPA.

Applies the SAME load wave to the sample app under two autoscalers and logs the
real metrics (replicas, CPU, request latency) over time:

    python deploy/run_experiment.py --mode rl    --duration 300
    python deploy/run_experiment.py --mode hpa   --duration 300

Then compare with deploy/compare_realcluster.py.

Load is generated by a built-in HTTP load generator that ramps up then down (a
traffic "wave"); Locust is the production-equivalent tool for the same role.
"""

import os
import sys
import csv
import time
import math
import random
import argparse
import threading
import subprocess
import urllib.request
from collections import deque

ROOT = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, ROOT)

from environment.custom_env import KubernetesEnv
from deploy.controller.rl_controller import (
    get_replicas, get_avg_cpu_millicores, scale_to, DEPLOYMENT, sh,
)

URL = "http://localhost:8090/work"
N_WORKERS = 60
RECENT = deque(maxlen=400)     # recent request latencies (seconds)
_intensity = 0.0               # 0..1 fraction of workers actively sending
_running = True


def worker():
    while _running:
        if random.random() < _intensity:
            t0 = time.perf_counter()
            try:
                urllib.request.urlopen(URL, timeout=5).read()
                RECENT.append(time.perf_counter() - t0)
            except Exception:
                RECENT.append(5.0)         # timeout/error counts as bad latency
        else:
            time.sleep(0.05)


def wave_intensity(progress):
    """Triangular traffic wave: ramps 0->1 by mid-run, back to ~0 by the end."""
    return 1.0 - abs(2 * progress - 1)     # peak at progress=0.5


def port_forward():
    p = subprocess.Popen(
        ["kubectl", "port-forward", f"svc/{DEPLOYMENT}", "8090:80"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(4)
    return p


def main():
    global _intensity, _running
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["rl", "hpa"], required=True)
    ap.add_argument("--duration", type=int, default=300)
    ap.add_argument("--interval", type=int, default=15)
    args = ap.parse_args()

    # reset to a clean starting point
    sh(["kubectl", "scale", "deployment", DEPLOYMENT, "--replicas=1"])
    if args.mode == "hpa":
        sh(["kubectl", "apply", "-f", os.path.join(ROOT, "deploy", "k8s", "hpa.yaml")])
    else:
        sh(["kubectl", "delete", "hpa", DEPLOYMENT, "--ignore-not-found"])
    time.sleep(5)

    engine = None
    if args.mode == "rl":
        from serving.inference_engine import InferenceEngine
        engine = InferenceEngine()

    pf = port_forward()
    threads = [threading.Thread(target=worker, daemon=True) for _ in range(N_WORKERS)]
    for t in threads:
        t.start()

    print(f"=== {args.mode.upper()} run | {args.duration}s ===")
    start = time.perf_counter()
    rows = []
    while True:
        elapsed = time.perf_counter() - start
        if elapsed >= args.duration:
            break
        progress = elapsed / args.duration
        _intensity = wave_intensity(progress)

        replicas = get_replicas()
        avg_cpu_m = get_avg_cpu_millicores()
        cpu_util = min(avg_cpu_m / 1000.0, 1.0)
        lat = sorted(RECENT)
        p95 = (lat[int(0.95 * len(lat))] if lat else 0.0)

        if args.mode == "rl":
            d = engine.decide(cpu_util=cpu_util, pods=max(replicas, 1),
                              queue_depth=cpu_util * KubernetesEnv.QUEUE_SCALE,
                              day_progress=progress)
            scale_to(replicas + {0: -1, 1: 0, 2: +1}[d["action"]])

        rows.append(dict(t=round(elapsed, 1), intensity=round(_intensity, 2),
                         replicas=replicas, avg_cpu_m=round(avg_cpu_m, 1),
                         p95_latency_s=round(p95, 3)))
        print(f"t={elapsed:6.1f}s load={_intensity:.2f} pods={replicas} "
              f"cpu={avg_cpu_m:6.1f}m p95={p95*1000:6.0f}ms")
        time.sleep(args.interval)

    _running = False
    pf.terminate()
    out = os.path.join(ROOT, "outputs", "realcluster", f"realcluster_{args.mode}.csv")
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=rows[0].keys())
        w.writeheader(); w.writerows(rows)
    print(f"\n✅ {args.mode} run -> {os.path.relpath(out, ROOT)} ({len(rows)} ticks)")


if __name__ == "__main__":
    main()
